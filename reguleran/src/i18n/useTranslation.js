export const useLanguageStore = create((set) => ({
  language: typeof window !== 'undefined' ? localStorage.getItem('reguleran-lang') || 'id' : 'id',
  setLanguage: (lang) => {
    if (typeof window !== 'undefined') localStorage.setItem('reguleran-lang', lang)
    set({ language: lang })
  },
  toggleLanguage: () => {
    set((state) => {
      const next = state.language === 'id' ? 'en' : 'id'
      if (typeof window !== 'undefined') localStorage.setItem('reguleran-lang', next)
      return { language: next }
    })
  }
}))

export function useTranslation() {
  const language = useLanguageStore((s) => s.language)
  const setLanguage = useLanguageStore((s) => s.setLanguage)
  const toggleLanguage = useLanguageStore((s) => s.toggleLanguage)

  function t(path) {
    const keys = path.split('.')
    let current = translations[language] || translations.id
    for (const key of keys) {
      if (current[key] === undefined) {
        let fallback = translations.id
        for (const fbKey of keys) {
          if (fallback && fallback[fbKey] !== undefined) fallback = fallback[fbKey]
          else return path
        }
        return fallback
      }
      current = current[key]
    }
    return current
  }

  return { t, language, setLanguage, toggleLanguage }
}
